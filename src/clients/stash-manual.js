// routehub — модуль clients/stash-manual.js
// КЛИЕНТСКИЙ СЛОЙ STASH, РУЧНОЙ ВЫБОР УЗЛА: имя группы «-Ручной», её
// состав и пара «ручная + fallback» на одну сеть. Раскладку по функциям
// делает clients/stash.js (buildGroups); здесь — то, что должно быть ОДНИМ
// источником и для генератора, и для тестов, и для
// сборщика scripts/routehub-stash-collect.js (там та же строка в MANUAL,
// сцепку держит tests/stash-collect-coupling.test.js). Отдельный модуль — по
// правилу проекта «модуль < 15 КБ»: clients/stash.js уже больше.
//
// ЗАЧЕМ (решение Дианы 25.09, проба ST19 на Stash 3.4.1). Диана выбирает
// узел функции руками, но ручной выбор не должен отключать автоматический
// уход с мёртвого узла, а обход должен оставаться последним резервом.
// ST19 показала: закрепление члена fallback через PUT /proxies к следующему
// чтению сбрасывается (причина не установлена), выбор в select держится
// ≥ 5 ч, а ОБЁРТКА работает — fallback, у которого первым членом стоит
// ручной select, пропускает его, когда выбранный там узел мёртв (≤ 25 мин),
// и возвращается к нему, когда узел ожил (≤ 20 мин). Отсюда схема:
//   RH-X-W-Ручной  select, рабочие узлы -W в том же порядке, БЕЗ обхода
//   RH-X-W         fallback: [RH-X-W-Ручной, прежний список, обход последним]
// Первый член select — лучший рабочий узел по баллу, поэтому, пока никто
// ничего не выбирал, группа ведёт себя как раньше. Обходных узлов в select
// нет: выбрать платный обход вручную нельзя, а замер ядра через select не
// добавляет ни одного обходного узла сверх тех, что уже в fallback.
// Кто и как ставит выбор (панель, плитки, автоматика Worker'а) — открыто;
// пока — сама Диана в интерфейсе Stash.

// Суффикс имени. Имя ручной группы — имя её fallback плюс суффикс, так что
// хвост -W/-C (по нему сборщик читает сеть у РОДИТЕЛЯ) у самого fallback не
// меняется, а ручную группу нельзя спутать с узлом: скобки «[» в ней нет.
const MANUAL_SUFFIX = '-Ручной';

function manualName(child) { return child + MANUAL_SUFFIX; }

// Ранг «только рабочие узлы»: обходной узел (tag 'bypass' — слово BYPASS_WORD
// в любом месте имени, util.js tagOf) из группы выпадает, остальным ранг
// оставлен прежним. orderNames сортирует по (ранг, балл, исходный порядок),
// поэтому порядок рабочих узлов совпадает с их порядком в fallback — это
// проверяет tests/clients-stash.test.js.
function workingOnly(rank) {
  return function (it, side) { return it.tag === 'bypass' ? -1 : rank(it, side); };
}

// ── ГРУППЫ ───────────────────────────────────────────────────────────
// Форма членства (А/Б) и fallback строятся в clients/stash.js и приходят
// сюда функциями: fill(g, names) — вписать членов в выбранной форме,
// child(name, names, head) — fallback той же формы с группами head перед
// узлами. Импорт из clients/stash.js дал бы цикл модулей.
// Форма (Б): ручная группа — use + filter по рабочим именам; в fallback она
// идёт явным `proxies:` рядом с use + filter (имени группы поставщик не
// знает). Ставит ли ядро явных членов раньше членов поставщика —
// документацией Stash не подтверждено; это часть открытого вопроса стенда о
// порядке в форме (Б) (раздел 11, пункт 1 сверки).

// Ручная группа — select без interval: её узлы замеряются и так, в fallback
// (задержка ядра общая на узел, BENCH_URL в clients/stash.js).
function manualGroup(name, names, fill) {
  return fill({ name: name, type: 'select' }, names);
}

// Пара «ручная + fallback» для одной сети.
// ПУСТОЙ РАБОЧИЙ НАБОР (одни обходные узлы или ни одного узла): select без
// членов Stash не разберёт — не загрузится весь профиль, — а подставить
// DIRECT значило бы менять маршрутизацию из генератора. Поэтому ручная
// группа тогда НЕ создаётся и в fallback не ставится: выбирать всё равно не
// из чего, а fallback остаётся ровно прежним. Висячей ссылки не возникает —
// обе стороны решаются одним условием.
function netPair(name, all, working, fill, child) {
  if (!working.length) return [child(name, all)];
  const man = manualName(name);
  return [manualGroup(man, working, fill), child(name, all, [man])];
}

export { MANUAL_SUFFIX, manualName, netPair, workingOnly };
