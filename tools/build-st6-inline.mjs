// Сборка «вшитого» варианта override ST6 для Stash.
//
// ЗАЧЕМ ГЕНЕРАТОР, А НЕ ГОТОВЫЙ ФАЙЛ В РЕПОЗИТОРИИ. Вшитый вариант — это тот
// же `probes/routehub-probe-stash6.js`, вложенный в YAML полем `payload`.
// Держать в репозитории вторую копию тех же 20 КБ значит завести дубль,
// который разойдётся с оригиналом при первой же правке пробы: так уже дважды
// терялись байты при ручном переносе. Источник истины один — файл пробы.
//
// ЗАПУСК:  node tools/build-st6-inline.mjs
// РЕЗУЛЬТАТ: plugins/RouteHub-Stash-ST6-inline.stoverride (в .gitignore)
//
// ФОРМАТ ПРОВЕРЕН ПО ДОКУМЕНТАЦИИ STASH:
//   `payload` — поле `script-providers`, НЕ `tiles` (docs/script/manage-script,
//   iOS/tvOS 3.2.5+); `tiles[].name` обязан совпадать с ключом провайдера
//   (docs/script/tile); интервал плитки задаётся секундами, значение -1 —
//   это синтаксис Loon, Stash такую плитку отбрасывает.

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'probes/routehub-probe-stash6.js');
const OUT = path.join(ROOT, 'plugins/RouteHub-Stash-ST6-inline.stoverride');

const HEAD = `name: "RouteHub ST6 — проба лазеек Stash"
desc: "Плитка на главном экране Stash: нажатие снимает пробу возможностей клиента. Скрипт вшит прямо в файл — ничего не скачивается. ТОЛЬКО ЧТЕНИЕ: политику, правила и узлы не меняет."
author: "RouteHub"
category: "RouteHub"

# ============================================================================
# ЭТОТ ФАЙЛ СОБРАН АВТОМАТИЧЕСКИ: tools/build-st6-inline.mjs
# Править здесь бесполезно — правится probes/routehub-probe-stash6.js.
#
# ЧТО ИСПРАВЛЕНО 24.08 (почему прошлые редакции не запускались)
#   1. Поле \`payload\` стояло внутри записи \`tiles:\`. У Stash оно там не
#      поддерживается: \`payload\` — поле \`script-providers\`, а \`tiles[].name\`
#      обязан совпадать с ключом провайдера. Ссылку на несуществующий скрипт
#      Stash молча отбрасывает — отсюда «скрипта нет и кнопки нет».
#   2. \`interval: -1\` в плитке — синтаксис Loon. В Stash интервал задаётся
#      секундами; отрицательное значение роняло плитку.
#   3. Плановое задание \`cron:\` убрано: оно требует поднятого туннеля и
#      здесь не нужно — плитка и есть кнопка запуска.
#
# ТРЕБОВАНИЕ: Stash iOS 3.2.5 и новее — раньше поля \`payload\` не было.
#
# ── УСТАНОВКА ──────────────────────────────────────────────────────────────
# Сохранить файл на телефон → Stash → Настройки → Override → добавить из
# файла. На главном экране появится плитка «RouteHub ST6». Нажать — проба
# отработает и покажет сводку прямо на плитке; полный отчёт (JSON) уйдёт в
# журнал Stash и в уведомление.
#
# ── УСЛОВИЯ ПРОГОНА ────────────────────────────────────────────────────────
# Туннель Stash должен быть поднят и по нему должен идти трафик: проба
# читает \`/connections\`, а он пуст без соединений. Включить Stash, минуту
# попользоваться телефоном обычным образом, и только потом нажимать плитку.
#
# После разведки override удалить — он нужен на один-два прогона.
# ============================================================================

script-providers:
  routehub-probe-stash6:
    interval: 86400
    payload: |
`;

const TAIL = `
tiles:
  - name: routehub-probe-stash6
    interval: 7200
    title: 'RouteHub ST6'
    content: 'Нажми — проба лазеек Stash'
    icon: 'key.viewfinder'
    backgroundColor: '#3A3A3C'
`;

const js = fs.readFileSync(SRC, 'utf8');
// Блочный скаляр YAML: каждая непустая строка сдвигается на 6 пробелов,
// пустые остаются по-настоящему пустыми (иначе появятся хвостовые пробелы).
const body = js.replace(/\n+$/, '').split('\n')
  .map((ln) => (ln.trim() ? '      ' + ln : '')).join('\n');

fs.writeFileSync(OUT, HEAD + body + '\n' + TAIL);
console.log('собран', path.relative(ROOT, OUT), fs.statSync(OUT).size, 'Б');
